/** SCSS/Vue style rules. Every place a project departs from the base is an option. */
import { fileURLToPath } from 'node:url';

import type { Config } from 'stylelint';

export type StylelintOptions = {
    /** Unit allowed for margin/padding/gap/border-radius. Defaults to `'em'`. */
    spacingUnit?: 'em' | 'rem';
    /** Properties that must reference a token instead of a literal. Defaults to colour only. */
    tokenProperties?: string[];
    /** Treat `0` as a reset rather than an untokenised value. Defaults to false. */
    ignoreZero?: boolean;
    /** Also ignore `currentcolor`, which is what `value-keyword-case` rewrites `currentColor` into before this rule sees it. Defaults to false. */
    lowercaseCurrentColor?: boolean;
    /** Flag `var(--x)` with no visible `--x`. Off where the tokens are generated by a SCSS loop no static analyser can follow. Defaults to true. */
    unknownCustomProperties?: boolean;
    /** Allow `block__element--modifier` class names. Defaults to false. */
    bem?: boolean;
    /** Ban SCSS color functions on `$color-*` aliases, which resolve to `var(--color-*)` and cannot be computed at build time. Defaults to false. */
    noScssColorFunctions?: boolean;
    /** Ban `@import` in favour of `@use`/`@forward`. Defaults to false. */
    noScssImport?: boolean;
    /** Ban `max-width` media features. Defaults to false. */
    mobileFirst?: boolean;
    /** Allow consecutive duplicate properties with different values — the CSS fallback idiom (`100vh` then `100dvh`). Defaults to false. */
    duplicateFallbacks?: boolean;
    /** Switch `no-unknown-custom-properties` off inside `**\/styles/_variables.scss`, where the aliases are declared rather than used. Defaults to false. */
    variablesOverride?: boolean;
    /** Globs for token/theme files that are read for context but not linted directly, so the tokens they declare are not reported as unknown. */
    referenceFiles?: string[];
    /** Parse `<style>` blocks in `.vue` files. Defaults to true. */
    vue?: boolean;
    /** Extra rules, merged last — the escape hatch. */
    rules?: Config['rules'];
    /** Extra overrides, appended last. */
    overrides?: Config['overrides'];
};

/**
 * Plugins resolved from here as absolute paths: Stylelint resolves bare names next to
 * the project's config, which would need the project to install them. `import.meta.resolve`
 * because stylelint-config-standard-scss is ESM-only.
 */
const dep = (name: string) => fileURLToPath(import.meta.resolve(name));

const SPACING_PROPERTIES = [
    'margin',
    'margin-top',
    'margin-bottom',
    'margin-left',
    'margin-right',
    'padding',
    'padding-top',
    'padding-bottom',
    'padding-left',
    'padding-right',
    'gap',
    'row-gap',
    'column-gap',
    'border-radius',
];

const BEM_PATTERN = '^[a-z][a-z0-9]*(-[a-z0-9]+)*(__[a-z][a-z0-9]*(-[a-z0-9]+)*)?(--[a-z][a-z0-9]*(-[a-z0-9]+)*)?$';

/** SCSS colour functions handed a `$color-*` alias — see `noScssColorFunctions`. */
const SCSS_COLOR_FUNCTION_PATTERN =
    '/(rgba|rgb|hsla|hsl|darken|lighten|saturate|desaturate|transparentize|opacify|fade-in|fade-out|adjust-color|scale-color|change-color|mix)\\(\\s*\\$color-/';


export function stylelint(options: StylelintOptions = {}): Config {
    const {
        spacingUnit = 'em',
        tokenProperties = ['/color$/', 'fill', 'stroke'],
        ignoreZero = false,
        lowercaseCurrentColor = false,
        unknownCustomProperties = true,
        bem = false,
        noScssColorFunctions = false,
        noScssImport = false,
        mobileFirst = false,
        duplicateFallbacks = false,
        variablesOverride = false,
        referenceFiles = [],
        vue = true,
        rules = {},
        overrides = [],
    } = options;

    const spacing = Object.fromEntries(SPACING_PROPERTIES.map((property) => [property, [spacingUnit]]));

    const ignoreValues = [
        'transparent',
        'currentColor',
        ...(lowercaseCurrentColor ? ['currentcolor'] : []),
        'inherit',
        'initial',
        'unset',
        'revert',
        'none',
        ...(ignoreZero ? ['0'] : []),
    ];

    return {
        extends: [dep('stylelint-config-standard-scss')],
        ...(referenceFiles.length
            ? {
                  referenceFiles: referenceFiles.map((files) => ({
                      files: [files],
                      customSyntax: dep('postcss-scss'),
                  })),
              }
            : {}),
        plugins: [dep('stylelint-scss'), dep('stylelint-declaration-strict-value')],
        rules: {
            // –– COLOR FUNCTIONS –––––––––––––––––––––––––––––––––––––––––––––––
            'color-function-notation': 'modern',

            // –– BEM ––––––––––––––––––––––––––––––––––––––––––––––––––––––––––
            ...(bem
                ? {
                      'selector-class-pattern': [
                          BEM_PATTERN,
                          {
                              message: 'Expected class selector to be kebab-case BEM (block__element--modifier)',
                          },
                      ],
                  }
                : {}),

            // –– UNITS –––––––––––––––––––––––––––––––––––––––––––––––––––––––––
            // Spacing and radius follow `spacingUnit`; both em and rem scale with the user's font size.
            'declaration-property-unit-allowed-list': {
                'font-size': ['rem'],
                'line-height': [],
                ...spacing,
                'min-width': ['%', 'px', 'vh', 'vw', 'dvh', 'dvw', 'ch'],
                'max-width': ['%', 'px', 'vh', 'vw', 'dvh', 'dvw', 'ch'],
                'min-height': ['%', 'px', 'vh', 'vw', 'dvh', 'dvw'],
                'max-height': ['%', 'px', 'vh', 'vw', 'dvh', 'dvw'],
                'width': ['px', '%', 'vh', 'vw', 'dvh', 'dvw'],
                'height': ['px', '%', 'vh', 'vw', 'dvh', 'dvw'],
                'top': ['px', '%'],
                'right': ['px', '%'],
                'bottom': ['px', '%'],
                'left': ['px', '%'],
                'blur': ['px'],
                'grid-template-columns': ['fr', 'rem', '%'],
                'grid-template-rows': ['fr', 'rem', '%'],
            },

            // –– NO VENDOR PREFIXES –––––––––––––––––––––––––––––––––––––––––––––––
            'property-no-vendor-prefix': true,
            'value-no-vendor-prefix': true,
            'selector-no-vendor-prefix': true,
            'at-rule-no-vendor-prefix': true,

            // –– SCSS VARIABLES –––––––––––––––––––––––––––––––––––––––––––––––
            'scss/dollar-variable-pattern': '^[a-z][a-z0-9-]*$',
            'scss/dollar-variable-empty-line-before': null,

            // –– LAYOUT –––––––––––––––––––––––––––––––––––––––––––––––––––––––––
            'property-no-unknown': [
                true,
                {
                    ignoreProperties: ['/^composes/'],
                },
            ],

            // –– SCSS NESTED PROPERTIES –––––––––––––––––––––––––––––––––––––––––––
            'scss/declaration-nested-properties': 'never',

            // –– DESIGN TOKENS –––––––––––––––––––––––––––––––––––––––––––––––
            // The unit rules constrain the unit, not the number; `tokenProperties` covers that.
            'no-unknown-custom-properties': unknownCustomProperties ? true : null,
            'scale-unlimited/declaration-strict-value': [
                tokenProperties,
                {
                    ignoreValues,
                    disableFix: true,
                },
            ],

            // –– THEMING: NO SCSS COLOR FUNCTIONS ON RUNTIME TOKENS ––––––––––––
            // `$color-*` resolves to `var(--color-*)`, which Sass cannot compute with.
            // Use `color-mix(in srgb, $color-accent 12%, transparent)` instead.
            ...(noScssColorFunctions
                ? {
                      'declaration-property-value-disallowed-list': [
                          { '/.*/': [SCSS_COLOR_FUNCTION_PATTERN] },
                          {
                              message:
                                  'Do not pass a $color-* alias to a SCSS colour function — it is `var(--color-*)`, which Sass cannot resolve at build time. Use CSS color-mix() instead.',
                          },
                      ],
                  }
                : {}),

            // –– MODULE SYSTEM ––––––––––––––––––––––––––––––––––––––––––––––––
            ...(noScssImport ? { 'at-rule-disallowed-list': ['import'] } : {}),

            // –– SCOPED STYLES –––––––––––––––––––––––––––––––––––––––––––––––
            'selector-max-specificity': ['1,4,1'],
            'selector-max-id': 1,

            // –– GENERAL BEST PRACTICES –––––––––––––––––––––––––––––––––––––
            'color-no-invalid-hex': true,
            'declaration-no-important': true,
            // Different-value duplicates are the fallback idiom (`100vh` then `100dvh`).
            'declaration-block-no-duplicate-properties': duplicateFallbacks
                ? [true, { ignore: ['consecutive-duplicates-with-different-values'] }]
                : true,
            'no-descending-specificity': null,
            'selector-pseudo-element-no-unknown': true,
            'media-feature-name-no-unknown': true,

            // –– MOBILE-FIRST –––––––––––––––––––––––––––––––––––––––––––––––
            // Breakpoints layer up with min-width. Only the media feature; the property is untouched.
            ...(mobileFirst ? { 'media-feature-name-disallowed-list': ['max-width'] } : {}),
            'at-rule-no-unknown': null,

            // –– IGNORE SCOPED STYLES SPECIFICITY FOR VUE –––––––––––––––––––––––––––––––––––––––––––
            'selector-pseudo-class-no-unknown': [
                true,
                {
                    ignorePseudoClasses: ['deep', 'global', 'v-deep', 'v-global'],
                },
            ],

            ...rules,
        },
        overrides: [
            ...(vue ? [{ files: ['**/*.vue'], customSyntax: dep('postcss-html') }] : []),
            // The `:root` declaring these tokens is in another file; the scss gate checks them.
            ...(variablesOverride
                ? [
                      {
                          files: ['**/styles/_variables.scss'],
                          rules: { 'no-unknown-custom-properties': null },
                      },
                  ]
                : []),
            ...overrides,
        ],
    };
}

export default stylelint();
