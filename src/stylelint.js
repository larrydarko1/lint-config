/**
 * SCSS/Vue style rules. The base is what every project agrees on; every place a
 * project deliberately departs (Quartz's rem spacing, Mosaic's generated tokens)
 * is an option rather than a fork of the file.
 */

const SPACING_PROPERTIES = [
    'margin',
    'margin-top',
    'margin-bottom',
    'margin-left',
    'margin-right',
    'padding',
    'padding-top',
    'padding-bottom',
    'padding-left',
    'padding-right',
    'gap',
    'row-gap',
    'column-gap',
    'border-radius',
];

const BEM_PATTERN = '^[a-z][a-z0-9]*(-[a-z0-9]+)*(__[a-z][a-z0-9]*(-[a-z0-9]+)*)?(--[a-z][a-z0-9]*(-[a-z0-9]+)*)?$';

/** SCSS colour functions handed a `$color-*` alias — see `noScssColorFunctions`. */
const SCSS_COLOR_FUNCTION_PATTERN =
    '/(rgba|rgb|hsla|hsl|darken|lighten|saturate|desaturate|transparentize|opacify|fade-in|fade-out|adjust-color|scale-color|change-color|mix)\\(\\s*\\$color-/';

/**
 * @param {object} [options]
 * @param {'em'|'rem'} [options.spacingUnit='em'] Unit allowed for margin/padding/gap/border-radius.
 * @param {string[]} [options.tokenProperties] Properties that must reference a token instead of a
 *   literal. Defaults to colour only; the full-stack projects add the type and radius scales.
 * @param {boolean} [options.ignoreZero=false] Treat `0` as a reset rather than an untokenised value.
 * @param {boolean} [options.lowercaseCurrentColor=false] Also ignore `currentcolor`, which is what
 *   `value-keyword-case` rewrites `currentColor` into before this rule sees it.
 * @param {boolean} [options.unknownCustomProperties=true] Flag `var(--x)` with no visible `--x`.
 *   Off where the tokens are generated by a SCSS loop no static analyser can follow.
 * @param {boolean} [options.bem=false] Allow `block__element--modifier` class names.
 * @param {boolean} [options.noScssColorFunctions=false] Ban SCSS colour functions on `$color-*`
 *   aliases, which resolve to `var(--color-*)` and cannot be computed at build time.
 * @param {boolean} [options.noScssImport=false] Ban `@import` in favour of `@use`/`@forward`.
 * @param {boolean} [options.mobileFirst=false] Ban `max-width` media features.
 * @param {boolean} [options.duplicateFallbacks=false] Allow consecutive duplicate properties with
 *   different values — the CSS fallback idiom (`100vh` then `100dvh`).
 * @param {boolean} [options.variablesOverride=false] Switch `no-unknown-custom-properties` off
 *   inside `**\/styles/_variables.scss`, where the aliases are declared rather than used.
 * @param {Array} [options.referenceFiles=[]] Stylelint `referenceFiles` entries (token/theme files
 *   read for context but not linted directly).
 * @param {boolean} [options.vue=true] Parse `<style>` blocks in `.vue` files.
 * @param {object} [options.rules={}] Extra rules, merged last — the escape hatch.
 * @param {Array} [options.overrides=[]] Extra overrides, appended last.
 */
export function stylelint(options = {}) {
    const {
        spacingUnit = 'em',
        tokenProperties = ['/color$/', 'fill', 'stroke'],
        ignoreZero = false,
        lowercaseCurrentColor = false,
        unknownCustomProperties = true,
        bem = false,
        noScssColorFunctions = false,
        noScssImport = false,
        mobileFirst = false,
        duplicateFallbacks = false,
        variablesOverride = false,
        referenceFiles = [],
        vue = true,
        rules = {},
        overrides = [],
    } = options;

    const spacing = Object.fromEntries(SPACING_PROPERTIES.map((property) => [property, [spacingUnit]]));

    const ignoreValues = [
        'transparent',
        'currentColor',
        ...(lowercaseCurrentColor ? ['currentcolor'] : []),
        'inherit',
        'initial',
        'unset',
        'revert',
        'none',
        ...(ignoreZero ? ['0'] : []),
    ];

    return {
        extends: ['stylelint-config-standard-scss'],
        ...(referenceFiles.length ? { referenceFiles } : {}),
        plugins: ['stylelint-scss', 'stylelint-declaration-strict-value'],
        rules: {
            // –– COLOR FUNCTIONS –––––––––––––––––––––––––––––––––––––––––––––––
            'color-function-notation': 'modern',

            // –– BEM ––––––––––––––––––––––––––––––––––––––––––––––––––––––––––
            // block, block__element, block--modifier. The default pattern rejects
            // the `--modifier` half, which is the part that carries the meaning.
            ...(bem
                ? {
                      'selector-class-pattern': [
                          BEM_PATTERN,
                          { message: 'Expected class selector to be kebab-case BEM (block__element--modifier)' },
                      ],
                  }
                : {}),

            // –– UNITS –––––––––––––––––––––––––––––––––––––––––––––––––––––––––
            // Spacing and radius follow `spacingUnit`: `em` anchors geometry to the
            // element's own text, `rem` to one app-wide anchor. Both scale with the
            // user's font-size preference, which is the part `px` gives up.
            'declaration-property-unit-allowed-list': {
                'font-size': ['rem'],
                'line-height': [],
                ...spacing,
                'min-width': ['%', 'px', 'vh', 'vw', 'dvh', 'dvw', 'ch'],
                'max-width': ['%', 'px', 'vh', 'vw', 'dvh', 'dvw', 'ch'],
                'min-height': ['%', 'px', 'vh', 'vw', 'dvh', 'dvw'],
                'max-height': ['%', 'px', 'vh', 'vw', 'dvh', 'dvw'],
                'width': ['px', '%', 'vh', 'vw', 'dvh', 'dvw'],
                'height': ['px', '%', 'vh', 'vw', 'dvh', 'dvw'],
                'top': ['px', '%'],
                'right': ['px', '%'],
                'bottom': ['px', '%'],
                'left': ['px', '%'],
                'blur': ['px'],
                'grid-template-columns': ['fr', 'rem', '%'],
                'grid-template-rows': ['fr', 'rem', '%'],
            },

            // –– NO VENDOR PREFIXES –––––––––––––––––––––––––––––––––––––––––––––––
            'property-no-vendor-prefix': true,
            'value-no-vendor-prefix': true,
            'selector-no-vendor-prefix': true,
            'at-rule-no-vendor-prefix': true,

            // –– SCSS VARIABLES –––––––––––––––––––––––––––––––––––––––––––––––
            'scss/dollar-variable-pattern': '^[a-z][a-z0-9-]*$',
            'scss/dollar-variable-empty-line-before': null,

            // –– LAYOUT –––––––––––––––––––––––––––––––––––––––––––––––––––––––––
            'property-no-unknown': [
                true,
                {
                    ignoreProperties: ['/^composes/'],
                },
            ],

            // –– SCSS NESTED PROPERTIES –––––––––––––––––––––––––––––––––––––––––––
            'scss/declaration-nested-properties': 'never',

            // –– DESIGN TOKENS –––––––––––––––––––––––––––––––––––––––––––––––
            // The unit rules above constrain the UNIT but not the NUMBER —
            // `font-size: 0.875rem` passes them while being exactly the hard-coded
            // value the standard forbids. `tokenProperties` closes that for the
            // scales a project has finished tokenising.
            'no-unknown-custom-properties': unknownCustomProperties ? true : null,
            'scale-unlimited/declaration-strict-value': [
                tokenProperties,
                {
                    ignoreValues,
                    disableFix: true,
                },
            ],

            // –– THEMING: NO SCSS COLOR FUNCTIONS ON RUNTIME TOKENS ––––––––––––
            // Every `$color-*` alias resolves to `var(--color-*)`, whose value only
            // exists at runtime. Handing one to a Sass colour function asks the
            // compiler to compute with a string it cannot see — `rgba($color-accent,
            // .12)` compiles to garbage or throws, and the failure is silent enough
            // to ship. `color-mix(in srgb, $color-accent 12%, transparent)` is the
            // runtime-computed, theme-aware equivalent.
            ...(noScssColorFunctions
                ? {
                      'declaration-property-value-disallowed-list': [
                          { '/.*/': [SCSS_COLOR_FUNCTION_PATTERN] },
                          {
                              message:
                                  'Do not pass a $color-* alias to a SCSS colour function — it is `var(--color-*)`, which Sass cannot resolve at build time. Use CSS color-mix() instead.',
                          },
                      ],
                  }
                : {}),

            // –– MODULE SYSTEM ––––––––––––––––––––––––––––––––––––––––––––––––
            // `@import` is deprecated in Sass and slated for removal; it also dumps
            // everything into one global namespace, which is what `@use`/`@forward`
            // exist to prevent.
            ...(noScssImport ? { 'at-rule-disallowed-list': ['import'] } : {}),

            // –– SCOPED STYLES –––––––––––––––––––––––––––––––––––––––––––––––
            'selector-max-specificity': ['1,4,1'],
            'selector-max-id': 1,

            // –– GENERAL BEST PRACTICES –––––––––––––––––––––––––––––––––––––
            'color-no-invalid-hex': true,
            'declaration-no-important': true,
            // Consecutive duplicates with DIFFERENT values are the CSS fallback
            // idiom — `min-height: 100vh` then `100dvh`, so a browser that does not
            // know the second keeps the first. Same-value duplicates stay an error.
            'declaration-block-no-duplicate-properties': duplicateFallbacks
                ? [true, { ignore: ['consecutive-duplicates-with-different-values'] }]
                : true,
            'no-descending-specificity': null,
            'selector-pseudo-element-no-unknown': true,
            'media-feature-name-no-unknown': true,

            // –– MOBILE-FIRST –––––––––––––––––––––––––––––––––––––––––––––––
            // Base styles target the smallest viewport; breakpoints only ever layer
            // UP with min-width. A max-width query means someone started from the
            // desktop layout and shrank it, which is the pattern this forbids.
            // (This constrains the media FEATURE only; `max-width` as a property is
            // untouched and still governed by the unit allow-list above.)
            ...(mobileFirst ? { 'media-feature-name-disallowed-list': ['max-width'] } : {}),
            'at-rule-no-unknown': null,

            // –– IGNORE SCOPED STYLES SPECIFICITY FOR VUE –––––––––––––––––––––––––––––––––––––––––––
            'selector-pseudo-class-no-unknown': [
                true,
                {
                    ignorePseudoClasses: ['deep', 'global', 'v-deep', 'v-global'],
                },
            ],

            ...rules,
        },
        overrides: [
            ...(vue ? [{ files: ['**/*.vue'], customSyntax: 'postcss-html' }] : []),
            // _variables.scss maps every `--token` to a `$variable`, but the `:root` that declares
            // them lives elsewhere, and stylelint resolves custom properties per file — so from
            // here every token looks undeclared. The real three-way check is the scss gate.
            ...(variablesOverride
                ? [{ files: ['**/styles/_variables.scss'], rules: { 'no-unknown-custom-properties': null } }]
                : []),
            ...overrides,
        ],
    };
}

export default stylelint();
